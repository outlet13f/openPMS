def q(v):
    """SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def j(v):
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def working(d: dt.date) -> bool:
    return d.isoweekday() <= 5 and d.isoformat() not in HOLIDAYS


def days(a: str, b: str) -> int:
    x, y = dt.date.fromisoformat(a), dt.date.fromisoformat(b)
    n = 0
    while x <= y:
        n += working(x)
        x += dt.timedelta(days=1)
    return max(n, 1)


def next_working(d: str, after=True) -> str:
    x = dt.date.fromisoformat(d) + dt.timedelta(days=1 if after else 0)
    while not working(x):
        x += dt.timedelta(days=1)
    return x.isoformat()


def add_working(start: str, duration: int) -> str:
    x = dt.date.fromisoformat(start)
    n = 1
    while n < duration or not working(x):
        x += dt.timedelta(days=1)
        if working(x):
            n += 1
    return x.isoformat()


def plain(html: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]*>", " ", html)).strip()


