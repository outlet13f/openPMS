"""Dev data: the work package custom fields of the fake data layer (frontend/src/api/fake/seed.ts), as
db/dev/V1001__dev_custom_fields.sql. Run from backend/: python scripts/gen_dev_custom_fields.py"""
import json
import os

from ids import uid

FIELDS = [
    # id, name, format, position, types, is_for_all, is_filterable, options
    ("cf-client", "고객사", "list", 1, ["t-task", "t-feature", "t-bug"], False, True,
     [("cfo-internal", "사내"), ("cfo-hanbit", "한빛은행"), ("cfo-mirae", "미래상사"), ("cfo-daon", "다온커머스")]),
    ("cf-reviewer", "검토자", "user", 2, ["t-task", "t-feature", "t-bug"], True, True, []),
    ("cf-points", "스토리 포인트", "integer", 3, ["t-task", "t-feature"], False, True, []),
    ("cf-relnote", "릴리스 노트 필요", "bool", 4, ["t-feature", "t-bug"], True, True, []),
    ("cf-link", "참고 링크", "link", 5, ["t-task", "t-milestone", "t-summary", "t-feature", "t-bug"], True, False, []),
]
PROJECT_FIELDS = [("p-web", "cf-client"), ("p-web", "cf-points")]
VALUES = {
    3: {"cf-client": "cfo-hanbit", "cf-reviewer": "u-junho"},
    4: {"cf-client": "cfo-hanbit", "cf-points": 8},
    8: {"cf-relnote": False, "cf-link": "https://example.com/a11y-report"},
    9: {"cf-points": 5, "cf-relnote": True},
    11: {"cf-client": "cfo-mirae"},
}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def ref(v):
    """Readable ids inside values (options, people) become their uuids."""
    if isinstance(v, str) and (v.startswith("cfo-") or v.startswith("u-")):
        return uid(v)
    return v


out = ["-- Generated by scripts/gen_dev_custom_fields.py: custom fields of the fake data layer (dev profile only).", ""]
for fid, name, fmt, pos, types, for_all, filterable, options in FIELDS:
    out.append(
        f"insert into custom_fields (id, entity, name, format, is_for_all, is_filterable, position) values "
        f"({q(uid(fid))}, 'work_package', {q(name)}, {q(fmt)}, {str(for_all).lower()}, {str(filterable).lower()}, {pos});"
    )
    for i, (oid, value) in enumerate(options, start=1):
        out.append(f"insert into custom_field_options (id, custom_field_id, value, position) values ({q(uid(oid))}, {q(uid(fid))}, {q(value)}, {i});")
    for t in types:
        out.append(f"insert into custom_field_types (custom_field_id, type_id) values ({q(uid(fid))}, {q(uid(t))});")
for p, f in PROJECT_FIELDS:
    out.append(f"insert into project_custom_fields (project_id, custom_field_id) values ({q(uid(p))}, {q(uid(f))});")
out.append("")
out.append("-- values on the seeded work packages; updated_at stays as seeded")
out.append("set local openpms.keep_updated_at = 'on';")
for n, values in VALUES.items():
    doc = {uid(k): ref(v) for k, v in values.items()}
    out.append(f"update work_packages set custom_values = {q(json.dumps(doc, ensure_ascii=False))}::jsonb where id = {q(uid(f'wp-{n}'))};")

path = os.path.join(os.path.dirname(__file__), "..", "src", "main", "resources", "db", "dev", "V1001__dev_custom_fields.sql")
with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path))
